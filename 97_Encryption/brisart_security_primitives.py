"""
File: brisart_security_primitives.py

Purpose
-------
The frozen BSR2 core: the 1024-bit permutation, the rate-32 sponge hash, the
legacy keyed MAC, the legacy iterated password KDF, subkey derivation, the
legacy counter stream, and the byte helpers (framing, XOR, comparison, hex).
Every function here is output-compatible with BSR2 Alpha 2/3; the frozen
known-answer vectors in tests/known_answer_vectors.json pin that behaviour.

Communication / relationships
-----------------------------
No project imports. Consumed by brisart_security_sponge.py (which reuses the
permutation through ``permute_unchecked``), brisart_security_drbg.py,
brisart_security_envelope.py (legacy v2 envelope), and the test suites.
tools/generate_bsr2_parameters.py regenerates the embedded parameters and
tests/test_bsr2_parameters.py checks they still match.

Settings / parameters
---------------------
MASK64, STATE_WORDS (16), RATE_BYTES (32), DEFAULT_ROUNDS (32)
BSR2_PARAMETER_SEED, ROUND_CONSTANTS (24), ROUND_INDEX_CONSTANT,
LANE_INDEX_CONSTANT, INITIAL_STATE_CONSTANT, ROTATIONS (8), WORD_PERMUTATION (16)
MAX_SPONGE_OUTPUT_BYTES   1024, unchanged legacy ceiling.
MAX_STREAM_BYTES          64 MiB ceiling for one legacy stream request.
MAX_LEGACY_KDF_ITERATIONS 10,000,000 ceiling so a hostile caller cannot pin a
                          process forever.
DEFAULT_KDF_ITERATIONS    120,000 (unchanged).

Edge cases
----------
* ``permute`` validates the state (exactly sixteen ints in [0, 2**64)) and the
  round count (a real int, not bool); internal callers use the unchecked path.
* Booleans are rejected anywhere an integer length or count is expected.
* Domain initial states are cached per domain; cached copies are never handed
  out, so callers cannot corrupt the cache.
* ``hex_decode`` accepts only canonical lowercase text.

Known limitations
-----------------
* Rate-32 legacy modes cost roughly fourteen permutation calls per 64 output
  bytes; use brisart_security_sponge.py for anything bulk.
* ``derive_password_key`` is the legacy time-hard KDF. It is not memory-hard;
  brisart_security_kdf.py provides BSR2-MHF-1 for new work.
* CPython integer arithmetic is not constant-time. ``constant_time_equal``
  avoids early exits but cannot promise side-channel resistance.
* No property here has been established by independent cryptanalysis.

Examples
--------
>>> from brisart_security_primitives import sponge_hash, keyed_mac
>>> len(sponge_hash(b"abc"))
32
>>> len(keyed_mac(bytes(32), b"message", 16))
16
"""

MASK64 = (1 << 64) - 1
STATE_WORDS = 16
RATE_BYTES = 32
DEFAULT_ROUNDS = 32
MAX_SPONGE_OUTPUT_BYTES = 1024
MAX_STREAM_BYTES = 64 * 1024 * 1024
DEFAULT_KDF_ITERATIONS = 120_000
MINIMUM_KDF_ITERATIONS = 10_000
MAX_LEGACY_KDF_ITERATIONS = 10_000_000

