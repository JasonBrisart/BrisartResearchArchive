ROTATIONS = (34, 5, 38, 37, 31, 50, 59, 17)
WORD_PERMUTATION = (6, 11, 12, 0, 5, 15, 2, 14, 3, 13, 4, 7, 10, 9, 8, 1)


class BrisartPrimitiveError(ValueError):
    pass


def _require_int(value, name: str) -> int:
    if type(value) is not int:
        raise BrisartPrimitiveError(f"{name} must be an integer")
    return value


def _require_bytes(value, name: str) -> bytes:
    if not isinstance(value, bytes):
        raise BrisartPrimitiveError(f"{name} must be bytes")
    return value


def rotate_left(value: int, amount: int) -> int:
    amount %= 64
    value &= MASK64
    return ((value << amount) | (value >> (64 - amount))) & MASK64


def _mix_pair(state: list[int], left: int, right: int, rotation: int) -> None:
    state[left] = (state[left] + state[right]) & MASK64
    state[right] = rotate_left(state[right] ^ state[left], rotation)


# ---------------------------------------------------------------------------
# Precomputed round schedule.
#
# The additive lane constant rotate_left(constant ^ (i * LANE), (7i + r) % 64)
# depends only on r mod lcm(24, 64) = 192, and every rotation index depends on
# r mod 8. Precomputing both removes ~600 Python-level calls per round without
# changing a single output bit (pinned by the known-answer vectors and by the
# reference-equivalence test in tests/test_primitives_hardening.py).
# ---------------------------------------------------------------------------
_SCHEDULE_PERIOD = 192
_LANE_ADDS = tuple(
    tuple(
        rotate_left(
            ROUND_CONSTANTS[r % len(ROUND_CONSTANTS)] ^ (i * LANE_INDEX_CONSTANT),
            (i * 7 + r) % 64,
        )
        for i in range(STATE_WORDS)
    )
    for r in range(_SCHEDULE_PERIOD)
)
_CROSS_ROTATIONS = tuple(
    tuple(ROTATIONS[(i + r) % 8] for i in range(STATE_WORDS)) for r in range(8)
)
_PAIR_ROTATIONS_A = tuple(ROTATIONS[i % 8] for i in range(8))
_PAIR_ROTATIONS_B = tuple(ROTATIONS[(i + 3) % 8] for i in range(8))


def permute_unchecked(state: list[int], rounds: int = DEFAULT_ROUNDS) -> None:
    """Apply the BSR2 permutation in place without validating arguments.

    Internal fast path. Callers must pass a list of sixteen 64-bit ints and a
    positive int round count. Output is bit-identical to the reference round
    function documented in docs/DESIGN.md.
    """
    s = state
    mask = MASK64
    constants = ROUND_CONSTANTS
    count = len(constants)
    pa = _PAIR_ROTATIONS_A
    pb = _PAIR_ROTATIONS_B
    perm = WORD_PERMUTATION
    for r in range(rounds):
        constant = constants[r % count]
        s[0] ^= constant
        s[15] ^= ((r + 1) * ROUND_INDEX_CONSTANT) & mask
        cross = _CROSS_ROTATIONS[r % 8]
        # Layer 1: adjacent pairs.
        for p in range(8):
            a = 2 * p
            b = a + 1
            x = (s[a] + s[b]) & mask
            s[a] = x
            y = s[b] ^ x
            k = pa[p]
            s[b] = ((y << k) | (y >> (64 - k))) & mask
        # Layer 2: half-state pairs.
        for a in range(8):
            b = a + 8
            x = (s[a] + s[b]) & mask
            s[a] = x
            y = s[b] ^ x
            k = cross[a]
            s[b] = ((y << k) | (y >> (64 - k))) & mask
        # Layer 3: adjacent pairs, shifted rotation schedule.
        for p in range(8):
            a = 2 * p
            b = a + 1
            x = (s[a] + s[b]) & mask
            s[a] = x
            y = s[b] ^ x
            k = pb[p]
            s[b] = ((y << k) | (y >> (64 - k))) & mask
        t = [s[i] for i in perm]
        adds = _LANE_ADDS[r % _SCHEDULE_PERIOD]
        for i in range(16):
            m = (t[(i + 1) & 15] & t[(i + 2) & 15]) ^ (
                (~t[(i + 3) & 15]) & t[(i + 5) & 15]
            )
            k = cross[i]
            m = ((m << k) | (m >> (64 - k))) & mask
            s[i] = ((t[i] ^ m) + adds[i]) & mask


def permute(state: list[int], rounds: int = DEFAULT_ROUNDS) -> None:
    if not isinstance(state, list) or len(state) != STATE_WORDS:
        raise BrisartPrimitiveError("state must contain sixteen words")
    for word in state:
        if type(word) is not int or word < 0 or word > MASK64:
            raise BrisartPrimitiveError("state words must be 64-bit integers")
    _require_int(rounds, "round count")
    if rounds <= 0:
        raise BrisartPrimitiveError("round count must be positive")
    permute_unchecked(state, rounds)


def frame(value: bytes) -> bytes:
    if not isinstance(value, bytes):
        raise BrisartPrimitiveError("framed value must be bytes")
    return len(value).to_bytes(8, "big") + value


def _pad(message: bytes) -> bytes:
    if not isinstance(message, bytes):
        raise BrisartPrimitiveError("message must be bytes")
    length_bits = len(message) * 8
    padded = bytearray(message)
    padded.append(0x80)
    padded.extend(b"\x00" * ((-(len(padded) + 8)) % RATE_BYTES))
    padded.extend(length_bits.to_bytes(8, "big"))
    return bytes(padded)


_INITIAL_STATE_CACHE: dict[bytes, tuple[int, ...]] = {}
_INITIAL_STATE_CACHE_LIMIT = 256


def _initial_state(domain: bytes) -> list[int]:
    _require_bytes(domain, "domain")
    cached = _INITIAL_STATE_CACHE.get(domain)
    if cached is not None:
        return list(cached)
    state = [
        (ROUND_CONSTANTS[index % len(ROUND_CONSTANTS)] ^ (index * INITIAL_STATE_CONSTANT)) & MASK64
        for index in range(STATE_WORDS)
    ]
    domain_block = frame(domain)
    for offset in range(0, len(domain_block), RATE_BYTES):
        block = domain_block[offset:offset + RATE_BYTES].ljust(RATE_BYTES, b"\x00")
        for index in range(4):
            state[index] ^= int.from_bytes(block[index * 8:(index + 1) * 8], "big")
        permute_unchecked(state)
    if len(_INITIAL_STATE_CACHE) < _INITIAL_STATE_CACHE_LIMIT:
        _INITIAL_STATE_CACHE[domain] = tuple(state)
    return state


def sponge_hash(message: bytes, output_bytes: int = 32, domain: bytes = b"BSR2/hash") -> bytes:
    _require_int(output_bytes, "output length")
    if output_bytes <= 0 or output_bytes > MAX_SPONGE_OUTPUT_BYTES:
        raise BrisartPrimitiveError("output length must be between 1 and 1024 bytes")
    state = _initial_state(domain)
    padded = _pad(message)
    for offset in range(0, len(padded), RATE_BYTES):
        state[0] ^= int.from_bytes(padded[offset:offset + 8], "big")
        state[1] ^= int.from_bytes(padded[offset + 8:offset + 16], "big")
        state[2] ^= int.from_bytes(padded[offset + 16:offset + 24], "big")
        state[3] ^= int.from_bytes(padded[offset + 24:offset + 32], "big")
        permute_unchecked(state)
    output = bytearray()
    while len(output) < output_bytes:
        for index in range(4):
            output.extend(state[index].to_bytes(8, "big"))
        if len(output) < output_bytes:
            permute_unchecked(state)
    return bytes(output[:output_bytes])


def keyed_mac(key: bytes, message: bytes, output_bytes: int = 32) -> bytes:
    if not isinstance(key, bytes) or len(key) < 16:
        raise BrisartPrimitiveError("MAC key must contain at least sixteen bytes")
    _require_bytes(message, "MAC message")
    inner = sponge_hash(frame(key) + frame(message), 64, b"BSR2/mac/inner")
    return sponge_hash(frame(key) + frame(inner) + frame(message), output_bytes, b"BSR2/mac/outer")


def derive_password_key(
    password: str,
    salt: bytes,
    iterations: int = DEFAULT_KDF_ITERATIONS,
    output_bytes: int = 32,
) -> bytes:
    if not isinstance(password, str) or not password:
        raise BrisartPrimitiveError("password must be a non-empty string")
    if not isinstance(salt, bytes) or len(salt) < 16:
        raise BrisartPrimitiveError("salt must contain at least sixteen bytes")
    _require_int(iterations, "iteration count")
    if iterations < MINIMUM_KDF_ITERATIONS:
        raise BrisartPrimitiveError("iteration count is below the research minimum")
    if iterations > MAX_LEGACY_KDF_ITERATIONS:
        raise BrisartPrimitiveError("iteration count exceeds the research maximum")
    try:
        password_bytes = password.encode("utf-8")
    except UnicodeEncodeError as exc:
        raise BrisartPrimitiveError("password is not valid UTF-8 text") from exc
    state = sponge_hash(frame(password_bytes) + frame(salt), 64, b"BSR2/kdf/start")
    for index in range(iterations):
        state = sponge_hash(
            frame(password_bytes)
            + frame(salt)
            + index.to_bytes(8, "big")
            + frame(state),
            64,
            b"BSR2/kdf/round",
        )
    return sponge_hash(frame(state) + frame(salt), output_bytes, b"BSR2/kdf/final")


def derive_subkey(master_key: bytes, salt: bytes, purpose: bytes, output_bytes: int = 32) -> bytes:
    _require_bytes(salt, "salt")
    _require_bytes(purpose, "purpose")
    return keyed_mac(master_key, frame(salt) + frame(purpose), output_bytes)


def stream_bytes(key: bytes, nonce: bytes, length: int) -> bytes:
    _require_int(length, "stream length")
    if length < 0:
        raise BrisartPrimitiveError("stream length cannot be negative")
    if length > MAX_STREAM_BYTES:
        raise BrisartPrimitiveError("stream length exceeds the size limit")
    _require_bytes(nonce, "nonce")
    output = bytearray()
    counter = 0
    framed_nonce = frame(nonce)
    while len(output) < length:
        output.extend(
            keyed_mac(
                key,
                framed_nonce + counter.to_bytes(8, "big"),
                64,
            )
        )
        counter += 1
    return bytes(output[:length])


def xor_bytes(left: bytes, right: bytes) -> bytes:
    if not isinstance(left, (bytes, bytearray)) or not isinstance(right, (bytes, bytearray)):
        raise BrisartPrimitiveError("XOR inputs must be bytes")
    if len(left) != len(right):
        raise BrisartPrimitiveError("XOR inputs must have equal length")
    if not left:
        return b""
    size = len(left)
    return (int.from_bytes(left, "big") ^ int.from_bytes(right, "big")).to_bytes(size, "big")


def constant_time_equal(left: bytes, right: bytes) -> bool:
    if not isinstance(left, bytes) or not isinstance(right, bytes):
        return False
    difference = len(left) ^ len(right)
    maximum = max(len(left), len(right))
    for index in range(maximum):
        a = left[index] if index < len(left) else 0
        b = right[index] if index < len(right) else 0
        difference |= a ^ b
    return difference == 0


def wipe(buffer: bytearray) -> None:
    """Overwrite a mutable buffer with zeros (best effort in CPython)."""
    if not isinstance(buffer, bytearray):
        raise BrisartPrimitiveError("only bytearray buffers can be wiped")
    for index in range(len(buffer)):
        buffer[index] = 0


_HEX_ALPHABET = "0123456789abcdef"
_HEX_VALUES = {character: value for value, character in enumerate(_HEX_ALPHABET)}


def hex_encode(data: bytes) -> str:
    if not isinstance(data, bytes):
        raise BrisartPrimitiveError("hex input must be bytes")
    characters = []
    for value in data:
        characters.append(_HEX_ALPHABET[value >> 4])
        characters.append(_HEX_ALPHABET[value & 15])
    return "".join(characters)


def hex_decode(text: str) -> bytes:
    if not isinstance(text, str) or len(text) % 2:
        raise BrisartPrimitiveError("hex input must have even length")
    if text != text.lower():
        raise BrisartPrimitiveError("hex input must be canonical lowercase")
    values = bytearray()
    lookup = _HEX_VALUES
    for index in range(0, len(text), 2):
        high = lookup.get(text[index])
        low = lookup.get(text[index + 1])
        if high is None or low is None:
            raise BrisartPrimitiveError("hex input contains invalid characters")
        values.append((high << 4) | low)
    return bytes(values)
